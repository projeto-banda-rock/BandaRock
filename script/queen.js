function openCrown() {
    document.getElementById('crownModal').style.display = 'flex';

}
function closeCrown() {
    document.getElementById('crownModal').style.display = 'none';

}
function openPanel() {
    document.getElementById('panelSide').classList.add('active');

}
function closePanel() {
    document.getElementById('panelSide').classList.remove('active');

}